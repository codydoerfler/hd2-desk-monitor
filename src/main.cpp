void setup() {
  Serial.begin(115200);
  delay(200);
  Serial.println(F("\n=== HD2 Major Order Monitor ==="));
  // Stamped from `git describe` by tools/fw_version.py. Deliberately not
  // guarded by an #ifndef: a build that somehow loses the flag should fail to
  // compile rather than quietly ship an image that lies about its version.
  Serial.printf("[boot] firmware %s\n", HD2_FW_VERSION);

  hud.begin();
  audio::begin();
  // Before the first sound is played, so a card that is present is already
  // usable by the boot chime's successors. A missing card is logged and
  // ignored -- every unit in the field today has an empty slot, and none of
  // them may be worse off for this firmware.
  storage::begin();
  touch::begin(hud.panel());
  maybeRecalibrateTouch();
  hud.showBoot("Connecting to WiFi...");

  // "I'm awake." Every boot, power-cycle included, once the panel is lit and
  // the amp is configured -- so the sound never arrives before there is
  // anything on screen to look at. Unconditional, including the first-ever
  // boot: unlike the update alert below, this is confirmation that power
  // reached the board, which is exactly what a fresh unit's owner wants.
  playBootChime();

  // Displayed clock times are UTC + this. Persisted in NVS alongside (but
  // separately from) the WiFi credentials, so it survives reflashing and is
  // set without recompiling.
  prefs.begin(HD2_PREFS_NS, false);

  // --- "the board was updated" ----------------------------------------------
  // An OTA reboots into the new image, so the update itself is never a moment
  // this code is running for -- the *next* boot is. Comparing the running
  // version against the one the last boot recorded is what makes that
  // detectable, and it covers a USB reflash the same way.
  //
  // A first-ever boot has nothing stored and stays silent: a device fresh out
  // of the box has not been updated, it has been set up, and announcing that
  // to an empty room is just noise.
  {
    const String ranBefore = prefs.getString(HD2_PREFS_FW_KEY, String());
    const String running = String(HD2_FW_VERSION);
    if (ranBefore.length() && ranBefore != running) {
      Serial.printf("[audio] updated %s -> %s\n", ranBefore.c_str(), running.c_str());
      playCompiledAlert();
    }
    if (ranBefore != running) prefs.putString(HD2_PREFS_FW_KEY, running);
  }

  model.utcOffsetMin =
      (int16_t)prefs.getShort(HD2_PREFS_TZ_KEY, kUtcOffsetMinutesDefault);
  char offsetField[10];
  formatUtcOffset(model.utcOffsetMin, offsetField, sizeof(offsetField));
  Serial.printf("[time] display offset %s (%d min from UTC)\n", offsetField,
                (int)model.utcOffsetMin);

  WiFiManager wm;
  wm.setDebugOutput(false);
  // Bounded so an unattended desk unit reboots and retries rather than sitting
  // in the config portal forever after a router outage.
  wm.setConfigPortalTimeout(kPortalTimeoutS);
  wm.setAPCallback([](WiFiManager *) { hud.showPortal(kPortalSsid, kPortalPass); });

  // Extra field on the portal page, under the network picker. It must outlive
  // autoConnect(), which is why it is declared here and not in a helper.
  WiFiManagerParameter offsetParam(
      "utcoff", "UTC offset in hours (e.g. -6, +1, +5:30)", offsetField,
      sizeof(offsetField) - 1);
  wm.addParameter(&offsetParam);

  if (!wm.autoConnect(kPortalSsid, kPortalPass)) {
    Serial.println(F("[wifi] portal timed out — rebooting"));
    hud.showBoot("Setup timed out. Restarting...");
    delay(2000);
    ESP.restart();
  }

  Serial.printf("[wifi] connected to %s as %s\n", WiFi.SSID().c_str(),
                WiFi.localIP().toString().c_str());
  WiFi.setAutoReconnect(true);
  WiFi.persistent(true);

  // If the portal ran, the field holds whatever was typed; if it didn't, it
  // still holds the value we pre-filled, so this is a no-op on a normal boot.
  // A value that doesn't parse is ignored rather than reset to UTC, so a typo
  // can't silently wipe a good setting.
  int16_t typed = 0;
  if (parseUtcOffset(offsetParam.getValue(), typed)) {
    if (typed != model.utcOffsetMin) {
      model.utcOffsetMin = typed;
      prefs.putShort(HD2_PREFS_TZ_KEY, typed);
      Serial.printf("[time] display offset saved: %d min from UTC\n", (int)typed);
    }
  } else {
    Serial.printf("[time] ignoring unparseable UTC offset \"%s\"; keeping %d min\n",
                  offsetParam.getValue(), (int)model.utcOffsetMin);
  }

  hud.showBoot("Synchronising clock...");
  syncClock();

  hud.showBoot("Contacting High Command...");
  hud.invalidate();

  // Downloading and flashing an image takes minutes and paints over the HUD,
  // which from the desk is indistinguishable from a crash unless the screen
  // says otherwise. Invalidating right here rather than after the update
  // covers the failure path too: if the flash fails the loop keeps running
  // with the notice still on the panel, and the renderer would otherwise see
  // an unchanged model and leave it there.
  ota.onUpdateStarting([](const char *message) {
    hud.showBoot(message);
    hud.invalidate();
  });
  ota.begin();

  pollDueMs = millis();  // poll immediately
}

void loop() {
  const uint32_t nowMs = millis();
  model.wifiUp = (WiFi.status() == WL_CONNECTED);

  // Nudge the WiFi stack if it has dropped. autoReconnect usually handles it;
  // this covers the cases where it gives up.
  if (!model.wifiUp && (int32_t)(nowMs - wifiRetryDueMs) >= 0) {
    Serial.println(F("[wifi] disconnected — reconnecting"));
    WiFi.reconnect();
    wifiRetryDueMs = nowMs + 15000;
  }

  if ((int32_t)(nowMs - pollDueMs) >= 0) poll();

  // Own timer, an hour apart, and a no-op on every iteration but those. It is
  // deliberately after the poll: the two share the device's one TLS connection
  // budget, and on the rare tick where both are due, data on screen matters
  // more than firmware freshness. A successful update never returns from here.
  ota.tick(model.wifiUp);

  const time_t nowUtc = time(nullptr);

  // Stale if the last poll failed, or if we simply haven't heard anything in
  // a couple of poll intervals (e.g. the ESP is up but the network isn't).
  if (model.haveData) {
    model.stale = (model.failCount > 0) ||
                  (nowUtc > 1600000000 && model.lastSuccess > 0 &&
                   (uint32_t)(nowUtc - model.lastSuccess) > kStaleAfterS);
  }

  // --- touch ---------------------------------------------------------------
  //
  // Usually the gesture already arrived, during the polling wait that ended
  // the last iteration. The direct poll() covers the rest of the beat -- a
  // contact that finished while this iteration was fetching or repainting.
  touch::Gesture gesture = pendingGesture;
  pendingGesture = touch::kNone;
  if (gesture == touch::kNone) gesture = touch::poll();

  if (model.overlay != kOverlayNone) {
    // Any contact dismisses. A tap is the documented gesture, but a swipe
    // aimed at a screen that has taken the whole panel means the same thing,
    // and refusing it would only read as the touch being broken.
    const bool acknowledged = (gesture != touch::kNone);
    const bool timedOut = (uint32_t)(nowMs - overlayShownMs) >= kOverlayFallbackMs;
    if (acknowledged || timedOut) {
      Serial.printf("[overlay] dismissed by %s\n", acknowledged ? "touch" : "timeout");
      const bool wasNewOrder = (model.overlay == kOverlayNewOrder);
      model.overlay = kOverlayNone;
      // Hand back to the new order's first objective rather than to wherever
      // the carousel had got to before the announcement interrupted it.
      if (wasNewOrder) hud.resetCarousel();
    }
  } else if (gesture == touch::kSwipeLeft) {
    hud.advancePage(model, +1);
  } else if (gesture == touch::kSwipeRight) {
    hud.advancePage(model, -1);
  }

  // --- overlays ------------------------------------------------------------
  //
  // Raised here rather than in poll() so an announcement goes up on a frame of
  // its own, after the model behind it has settled.
  //
  // After the dismissal check above, deliberately. Draining the queue first
  // would let one gesture clear an announcement and the one behind it in the
  // same iteration -- the second would be acknowledged before it was ever
  // drawn. Each one gets its own frame and its own dismissal.
  if (model.overlay == kOverlayNone && overlayQueueLen > 0) {
    model.overlay = overlayQueue[0];
    model.overlaySubject = overlayQueueSubject[0];
    overlayQueue[0] = overlayQueue[1];
    overlayQueueSubject[0] = overlayQueueSubject[1];
    overlayQueueLen--;
    overlayShownMs = nowMs;
    overlaySoundPending = true;
  }

  hud.update(model, nowUtc);

  // Sound follows the frame, always. Playback blocks for the length of the
  // clip, so firing before the repaint would announce a screen that is not on
  // the panel yet -- the same reason the new-order alert was queued before
  // there were overlays to queue with it.
  if (overlaySoundPending) {
    overlaySoundPending = false;
    playOverlayAlert(model.overlay);
  }

  pendingGesture = waitWithTouch(200);
}
