// Raised by poll(), shown by loop(). At most two can come out of a single
// poll -- the outgoing order's verdict and the incoming order's announcement,
// which is the ordinary case when High Command replaces one with the next --
// and they have to be seen in that order, so this is a queue and not a slot.
static OverlayKind overlayQueue[2] = {kOverlayNone, kOverlayNone};
static MajorOrder overlayQueueSubject[2];
static uint8_t overlayQueueLen = 0;

// millis() when the overlay on screen went up, and whether its clip still owes
// a play. Same queue-then-fire discipline as alertPending: sound follows the
// repaint, never leads it.
static uint32_t overlayShownMs = 0;
static bool overlaySoundPending = false;

// How long an overlay waits before giving up on being acknowledged.
//
// Touch is the intended way out and this is a safety net, not a feature: a
// panel that has stopped reading must not be able to strand the HUD on a
// verdict forever. One poll interval is the natural length -- it is the
// "dismiss on the next successful poll" fallback the brief suggested, arrived
// at by the clock instead of by the network, so it holds even if the network
// is also gone.
static const uint32_t kOverlayFallbackMs = (uint32_t)HD2_POLL_INTERVAL_S * 1000UL;

static void queueOverlay(OverlayKind kind, const MajorOrder &subject) {
  if (overlayQueueLen >= 2) return;  // cannot happen; not a reason to corrupt
  overlayQueue[overlayQueueLen] = kind;
  overlayQueueSubject[overlayQueueLen] = subject;
  overlayQueueLen++;
}

static bool allTasksComplete(const MajorOrder &o) {
  if (o.taskCount <= 0) return false;  // nothing to complete is not a success
  for (int i = 0; i < o.taskCount; i++)
    if (!o.tasks[i].complete) return false;
  return true;
}

// Did the order that was on screen just end, and how did it go?
//
// The API has no outcome field and no history endpoint: an assignment that
// ends simply stops being listed. So the verdict is inferred from the last
// state this device saw before it vanished.
//
// `prev` is the outgoing model.order, `next` what this poll returned. This is
// only safe because fetchMajorOrder() failing aborts the poll before here --
// so `next.valid == false` means the API said there is no order, never that
// the request failed. A dropped connection must not read as a lost war.
//
// The brief's two rules overlap on one case: an order whose expiration passes
// with every task done. Read literally, "expiration has passed -> FAILURE"
// would call that a loss. It is plainly a win, so completion is tested first
// and the deadline only decides orders that did not finish.
static OverlayKind classifyOrderOutcome(const MajorOrder &prev, const MajorOrder &next,
                                        time_t nowUtc) {
  if (!prev.valid) return kOverlayNone;

  const bool stillListed = next.valid && next.id == prev.id;
  if (stillListed) {
    // Still on the feed. Only a passed deadline says anything here, and only
    // about an order that has not finished -- a completed one is left alone
    // until it leaves, where it will be read as the success it is.
    const bool expired = prev.expiration > 0 && nowUtc > 1600000000 &&
                         nowUtc >= prev.expiration;
    if (expired && !allTasksComplete(next)) return kOverlayFailure;
    return kOverlayNone;
  }

  // Gone: replaced by a different id, or the feed is empty now.
  return allTasksComplete(prev) ? kOverlaySuccess : kOverlayFailure;
}

// A verdict is announced once. Without this the FAILURE branch above would
// re-fire on every poll for as long as an expired order stayed on the feed,
// and a device left alone overnight would come back to a panel that had been
// shouting at an empty room since 2am.
static int32_t verdictAnnouncedFor = 0;

static storage::Clip overlayClip(OverlayKind k) {
  switch (k) {
    case kOverlaySuccess: return storage::kClipSuccess;
    case kOverlayFailure: return storage::kClipFailure;
    default:              return storage::kClipNewOrder;
  }
}

// The voice for whichever announcement just went up.
//
// The card's clip wins when there is one, because it is specific to this event
// where the compiled-in line is the generic "go look at the screen" -- the
// whole point of the SD card is that the three events stop sounding alike.
// playClip() returns false for no card, no file, or a file this reader will
// not play, and all three land on the same fallback: a unit with no card still
// says something, it just cannot say which thing happened.
static void playOverlayAlert(OverlayKind kind) {
  if (kind == kOverlayNone) return;
  if (!storage::playClip(overlayClip(kind))) playCompiledAlert();
}

// Power-on acknowledgement.
//
// Cody's call, overriding the earlier design here: this plays the same clip
// as a new Major Order announcement (SD card kClipNewOrder, falling back to
// the compiled hellpods line with no card) rather than a distinct chime, so
// every plug-in sounds like the event it is standing in for. An
// update-detected boot below still layers the update alert on top, so that
// remains audible as a second, distinct sound after this one.
static void playBootChime() {
  playOverlayAlert(kOverlayNewOrder);
}

