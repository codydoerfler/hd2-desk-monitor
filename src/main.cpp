static void onPollFailed(const char *what) {
  model.failCount++;
  model.stale = true;
  Serial.printf("[poll] FAILED (%s): %s — retry in %us\n", what,
                api.lastError().c_str(), backoffS);
  pollDueMs = millis() + backoffS * 1000UL;
  backoffS = min(backoffS * 2, kBackoffMaxS);
}

// The planet record the last good poll left for `index`, or nullptr. Used to
// ride out a single flaky request without blanking a target card.
static const PlanetInfo *cachedPlanet(int32_t index) {
  for (int i = 0; i < model.order.taskCount; i++) {
    const PlanetInfo &p = model.order.tasks[i].planet;
    if (p.valid && p.index == index) return &p;
  }
  return nullptr;
}

// --- Rate history -----------------------------------------------------------
//
// The card quotes a %-per-hour figure that the API does not publish, so it is
// measured here by keeping one earlier snapshot per target and letting the
// renderer diff it against the live one. Called with `next` fully populated but
// *before* it replaces model.order, which is what makes the old snapshots still
// reachable.
static void rollRateHistory(const MajorOrder &next) {
  // A different order means different targets; anything held over would diff
  // two unrelated planets and invent a swing that never happened.
  if (next.id != model.historyOrderId) {
    for (int i = 0; i < kMaxOrderTasks; i++) model.history[i] = RateSample();
    model.historyOrderId = next.id;
    return;
  }

  for (int i = 0; i < kMaxOrderTasks; i++) {
    RateSample &h = model.history[i];
    if (i >= next.taskCount || !next.tasks[i].planet.valid) {
      h = RateSample();
      continue;
    }
    const PlanetInfo &np = next.tasks[i].planet;
    if (h.planetIndex != np.index) h = RateSample();

    // Advance only when the incoming observation is genuinely newer than the
    // one already on screen. A poll whose planet fetch failed carries the
    // cached snapshot — and its original timestamp — forward unchanged; if that
    // were allowed to shift the history the next good poll would diff a sample
    // against itself and the readout would blink out for no reason.
    const PlanetInfo *prev = cachedPlanet(np.index);
    if (!prev || !prev->valid) continue;
    if (prev->observedAt <= h.at || prev->observedAt >= np.observedAt) continue;

    h.valid = true;
    h.planetIndex = prev->index;
    h.at = prev->observedAt;
    h.libPct = prev->liberation;
    h.haveEvent = prev->event.active;
    h.eventPct = prev->event.defended();
    h.eventEnd = prev->event.endTime;
  }

  // Count-style progress, written after the loop above rather than inside it,
  // and that ordering is the whole point: that loop wipes a sample outright
  // whenever a task's planet cannot be resolved, and a count objective's
  // progress has to outlive exactly that case. It arrives with the assignments
  // payload, so every successful poll has it — while a planet the API holds no
  // record of (it 404s indices missing from its static table, which is the
  // normal state of a newly-added planet) fails on every poll, not one.
  //
  // The previous reading is model.order's, taken at model.lastSuccess: neither
  // has been overwritten yet, same as the planet pass above relies on.
  for (int i = 0; i < kMaxOrderTasks; i++) {
    RateSample &h = model.history[i];
    h.haveCount = false;
    h.countAt = 0;
    h.countPct = 0.0f;

    if (model.lastSuccess <= 0) continue;  // nothing polled yet: no baseline
    if (i >= next.taskCount || i >= model.order.taskCount) continue;
    // Both readings must be the same kind of count for the diff to mean
    // anything -- a task edited in place, or a goal revised mid-order, would
    // otherwise read as a jump in progress that never happened.
    if (!taskIsCount(next.tasks[i]) || !taskIsCount(model.order.tasks[i])) continue;
    if (next.tasks[i].taskType != model.order.tasks[i].taskType) continue;
    if (next.tasks[i].goal != model.order.tasks[i].goal) continue;

    h.haveCount = true;
    h.countAt = model.lastSuccess;
    h.countPct = taskPercent(model.order.tasks[i]);
  }
}

// Same invariant as rollRateHistory() above — only advance a sample when the
// incoming observation is genuinely newer, reset rather than diff across a
// different planet — but matched by planet index rather than array position:
// the campaigns list is top-N by player count, so which planet sits in slot i
// can reshuffle poll to poll (a planet dropping out of the top N and a
// different one taking its slot included). Called with `next` fully
// populated but before it replaces model.campaigns, same as above.
static void rollCampaignHistory(const PlanetInfo next[], int nextCount) {
  RateSample nextHistory[kMaxCampaigns];

  for (int i = 0; i < nextCount; i++) {
    RateSample h;
    const PlanetInfo *prev = nullptr;
    for (int j = 0; j < model.campaignCount; j++) {
      if (model.campaigns[j].valid && model.campaigns[j].index == next[i].index) {
        prev = &model.campaigns[j];
        h = model.campaignHistory[j];
        break;
      }
    }
    if (h.planetIndex != next[i].index) h = RateSample();

    if (prev && prev->valid && prev->observedAt > h.at &&
        prev->observedAt < next[i].observedAt) {
      h.valid = true;
      h.planetIndex = prev->index;
      h.at = prev->observedAt;
      h.libPct = prev->liberation;
    }
    nextHistory[i] = h;
  }

  for (int i = 0; i < nextCount; i++) model.campaignHistory[i] = nextHistory[i];
  for (int i = nextCount; i < kMaxCampaigns; i++) model.campaignHistory[i] = RateSample();
}

static void poll() {
  if (WiFi.status() != WL_CONNECTED) {
    onPollFailed("wifi down");
    return;
  }

  Serial.println(F("[poll] fetching assignments"));
  MajorOrder order;
  if (!api.fetchMajorOrder(order)) {
    onPollFailed("assignments");
    return;
  }

  // An empty assignments array is a valid state, not a failure: it just means
  // there is no Major Order right now. order.valid stays false and the HUD
  // shows the idle screen.
  //
  // One lookup per task: a "defend three planets" order names three different
  // planets and dropping all but the first is exactly the bug this loop
  // exists to avoid. kInterRequestDelayMs is sized for the resulting burst.
  if (order.valid) {
    for (int i = 0; i < order.taskCount; i++) {
      OrderTask &t = order.tasks[i];
      if (t.planetIndex < 0) continue;  // galaxy-wide objective, nothing to fetch

      delay(kInterRequestDelayMs);
      Serial.printf("[poll] fetching planet %d (task %d/%d, type %d)\n",
                    (int)t.planetIndex, i + 1, order.taskCount, (int)t.taskType);
      if (api.fetchPlanet(t.planetIndex, t.planet)) {
        // Time-base for the %-per-hour readouts. Left at 0 until NTP has landed
        // so a pre-sync boot cannot stamp a sample with a 1970 date.
        const time_t now = time(nullptr);
        if (now > 1600000000) t.planet.observedAt = now;
      } else {
        Serial.printf("[poll] planet lookup failed: %s\n", api.lastError().c_str());
        // The cached record is copied whole, timestamp included, so it stays
        // honestly dated as the older observation it is.
        const PlanetInfo *prev = cachedPlanet(t.planetIndex);
        if (prev) t.planet = *prev;
      }
    }
  }

  // With no Major Order there is no task list and therefore no planet, so the
  // screen would have nothing on it but a placeholder. The campaigns feed
  // fills the carousel instead. An active order owns the screen outright, so
  // this costs a request only in the state that would otherwise be idle and
  // the steady-state budget is unchanged.
  PlanetInfo campaigns[kMaxCampaigns];
  int campaignCount = 0;
  if (!order.valid) {
    delay(kInterRequestDelayMs);
    Serial.println(F("[poll] no order — fetching campaigns"));
    if (api.fetchCampaigns(campaigns, kMaxCampaigns, campaignCount)) {
      const time_t now = time(nullptr);
      for (int i = 0; i < campaignCount; i++) {
        if (now > 1600000000) campaigns[i].observedAt = now;
      }
      Serial.printf("[poll] campaigns: %d found, top %s at %.2f%% lib, %u divers\n",
                    campaignCount, campaignCount ? campaigns[0].name.c_str() : "n/a",
                    campaignCount ? campaigns[0].liberation : 0.0f,
                    campaignCount ? (unsigned)campaigns[0].playerCount : 0U);
    } else {
      // Not an error: a quiet galaxy, or the fetch failed. Either way the
      // previous set is better than blanking the screen.
      Serial.printf("[poll] campaigns lookup: %s\n", api.lastError().c_str());
      campaignCount = model.campaignCount;
      for (int i = 0; i < campaignCount; i++) campaigns[i] = model.campaigns[i];
    }
  }

  // War stats are garnish — a failure here never fails the poll, and we keep
  // whatever we had before.
  delay(kInterRequestDelayMs);
  WarStats war;
  if (!api.fetchWar(war)) {
    Serial.printf("[poll] war stats failed: %s\n", api.lastError().c_str());
    war = model.war;
  }

  // A Major Order this device has not seen before. Gated on haveData so the
  // first poll after a power cycle stays quiet -- the order that was already
  // running when the board booted is not news, and without this every outage
  // and every reboot would announce itself.
  const bool orderIsNew = order.valid && model.haveData && order.id != model.order.id;

  // How the outgoing order ended, if it did. Gated on haveData for the same
  // reason as orderIsNew: on the first poll after a reboot there is no
  // "before" to compare against, and an empty model.order would otherwise be
  // read as an order that vanished.
  //
  // Deliberately evaluated here, against model.order, before the assignment
  // below overwrites it.
  if (model.haveData) {
    const OverlayKind verdict =
        classifyOrderOutcome(model.order, order, time(nullptr));
    if (verdict != kOverlayNone && verdictAnnouncedFor != model.order.id) {
      verdictAnnouncedFor = model.order.id;
      Serial.printf("[order] %d \"%s\" -> %s\n", (int)model.order.id,
                    model.order.title.c_str(),
                    verdict == kOverlaySuccess ? "SUCCESS" : "FAILURE");
      queueOverlay(verdict, model.order);
    }
  }

  // Both read the *outgoing* model.order/model.campaigns, so they have to run
  // before those are overwritten below.
  rollRateHistory(order);
  rollCampaignHistory(campaigns, campaignCount);

  for (int i = 0; i < campaignCount; i++) model.campaigns[i] = campaigns[i];
  for (int i = campaignCount; i < kMaxCampaigns; i++) model.campaigns[i] = PlanetInfo();
  model.campaignCount = (uint8_t)campaignCount;
  model.order = order;
  model.war = war;
  model.haveData = true;
  model.stale = false;
  model.failCount = 0;
  model.lastSuccess = time(nullptr);

  backoffS = kBackoffMinS;
  pollDueMs = millis() + (uint32_t)HD2_POLL_INTERVAL_S * 1000UL;

  if (order.valid) {
    Serial.printf("[poll] OK — \"%s\", %d target(s), heap %u\n", order.title.c_str(),
                  order.taskCount, (unsigned)ESP.getFreeHeap());
    for (int i = 0; i < order.taskCount; i++) {
      const OrderTask &t = order.tasks[i];
      // Liberation is only quoted for the task type it means something for.
      if (t.planet.valid && t.planet.event.active) {
        Serial.printf("  [%d] type %d  %s  %.4f%% defended vs %s (%u hazard(s))\n",
                      i + 1, (int)t.taskType, t.planet.name.c_str(),
                      t.planet.event.defended(), t.planet.event.faction.c_str(),
                      (unsigned)t.planet.hazardCount);
      } else if (taskIsLiberation(t.taskType) && t.planet.valid) {
        Serial.printf("  [%d] type %d  %s  %.1f%% liberated\n", i + 1, (int)t.taskType,
                      t.planet.name.c_str(), t.planet.liberation);
      } else {
        Serial.printf("  [%d] type %d  %s  %s (owner %s)\n", i + 1, (int)t.taskType,
                      t.planet.valid ? t.planet.name.c_str() : "n/a",
                      t.complete ? "complete" : "incomplete",
                      t.planet.valid ? t.planet.owner.c_str() : "?");
      }
    }
  } else {
    Serial.printf("[poll] OK — no active Major Order, heap %u\n",
                  (unsigned)ESP.getFreeHeap());
  }

  // Queued rather than shown here: poll() runs before the frame that draws
  // this order, and an alert that finishes while the panel still shows the
  // previous one has told you to look at the wrong thing. loop() raises the
  // overlay and fires its clip once the repaint has landed.
  if (orderIsNew) {
    Serial.printf("[order] new Major Order %d — \"%s\"\n", (int)order.id,
                  order.title.c_str());
    queueOverlay(kOverlayNewOrder, order);
  }
}

